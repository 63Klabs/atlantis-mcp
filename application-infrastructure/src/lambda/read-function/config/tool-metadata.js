/**
 * Tool Metadata Registry
 *
 * Single source of truth for per-tool discovery metadata: display title,
 * behavioral annotations, category, trigger keywords, related tools,
 * when-to-use / when-not-to-use guidance, and structured usage examples for
 * every tool served by this MCP server.
 *
 * This module validates the registry once at load time via
 * `validateRegistry()` so that a malformed registry — a manifest tool with
 * no entry, an entry naming a tool that does not exist, or an entry missing
 * a required field — fails initialization fast, following the
 * `agent-asset-types.js` precedent.
 *
 * Every tool in this server is read-only and none reach an open-ended
 * external system at call time (all reads are against this server's own S3
 * buckets and DynamoDB tables), so `annotations.readOnlyHint` is `true` and
 * `annotations.openWorldHint` is `false` for every entry (Requirement 2.5).
 *
 * @module config/tool-metadata
 */

/**
 * @typedef {Object} ToolAnnotations
 * @property {boolean} readOnlyHint - True for every tool in this server; none mutate state
 * @property {boolean} openWorldHint - False for every tool in this server; none reach an open-ended external system at call time
 */

/**
 * @typedef {Object} ToolExample
 * @property {string} description - Short human-readable description of what the example demonstrates
 * @property {Object} arguments - A concrete, valid `arguments` payload for a `tools/call` of this tool
 */

/**
 * @typedef {Object} ToolMetadataEntry
 * @property {string} title - Human-readable display title (Requirement 2.1)
 * @property {ToolAnnotations} annotations - Behavioral annotations
 * @property {string} category - Short grouping label (e.g. 'templates', 'documentation')
 * @property {string[]} keywords - Trigger terms an agent would use when deciding to call this tool
 * @property {string[]} relatedTools - Names of other tools commonly used before/after this one
 * @property {string} whenToUse - Guidance on when to call this tool
 * @property {string} whenNotToUse - Guidance on when NOT to call this tool, pointing to the better alternative
 * @property {ToolExample[]} examples - At least one structured usage example
 */

