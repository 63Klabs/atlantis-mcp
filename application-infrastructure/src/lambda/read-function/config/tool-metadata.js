/**
 * The seven fields every `TOOL_METADATA` entry must declare with a
 * non-empty value. `annotations` is validated as an object with the two
 * required boolean hint fields; `keywords`, `relatedTools`, and `examples`
 * are validated as arrays (an empty `relatedTools` is permitted — a tool may
 * legitimately have no related tools — but `keywords` and `examples` must be
 * non-empty).
 * @constant {string[]}
 */
const REQUIRED_FIELDS = ['title', 'annotations', 'category', 'keywords', 'relatedTools', 'whenToUse', 'whenNotToUse', 'examples'];

/**
 * Check whether a value is a non-empty string (ignoring leading/trailing
 * whitespace-only content).
 *
 * @param {*} value - Value to check
 * @returns {boolean} True when `value` is a string with non-whitespace content
 */
function isNonEmptyString(value) {
  return typeof value === 'string' && value.trim() !== '';
}

/**
 * Validate a single field of a `TOOL_METADATA` entry against the shape it
 * is required to have.
 *
 * @param {string} field - Field name being validated
 * @param {*} value - Field value
 * @returns {boolean} True when the value satisfies the field's required shape
 */
function isValidField(field, value) {
  switch (field) {
    case 'title':
    case 'category':
    case 'whenToUse':
    case 'whenNotToUse':
      return isNonEmptyString(value);
    case 'annotations':
      return !!value && typeof value === 'object'
        && typeof value.readOnlyHint === 'boolean'
        && typeof value.openWorldHint === 'boolean';
    case 'keywords':
      return Array.isArray(value) && value.length > 0 && value.every(isNonEmptyString);
    case 'relatedTools':
      return Array.isArray(value) && value.every(isNonEmptyString);
    case 'examples':
      return Array.isArray(value) && value.length > 0 && value.every((ex) =>
        !!ex && typeof ex === 'object' && isNonEmptyString(ex.description) && !!ex.arguments && typeof ex.arguments === 'object'
      );
    default:
      return false;
  }
}

/**
 * Resolve the combined set of tool names this server actually serves:
 * the literal `settings.tools.availableToolsList` entries plus the
 * registry-driven agent-asset tools. Both inputs are required lazily
 * (rather than at module top level) to avoid a load-order assumption
 * between `tool-metadata.js`, `settings.js`, and `agent-asset-types.js`.
 *
 * @returns {string[]} Every tool name this server serves
 */
function getManifestToolNames() {
  // >! Required lazily: settings.js already requires agent-asset-types.js
  // >! and appends its generated tool definitions to availableToolsList,
  // >! so requiring settings.js alone is sufficient and avoids double-listing.
  const settings = require('./settings');
  return settings.tools.availableToolsList.map((tool) => tool.name);
}

/**
 * Validate a `TOOL_METADATA` registry against the server's actual tool
 * manifest.
 *
 * Throws when a tool served by the manifest has no registry entry, when a
 * registry entry names a tool that does not exist in the manifest, or when
 * an entry is missing a required field (`title`, `annotations`, `category`,
 * `keywords`, `relatedTools`, `whenToUse`, `whenNotToUse`, or at least one
 * `examples` entry). Runs once at module load (see bottom of this file) so a
 * malformed registry fails initialization before any tool definition is
 * served, following the `agent-asset-types.js` `validateRegistry()`
 * precedent (Requirement 2.1, 2.2).
 *
 * @param {Object.<string, ToolMetadataEntry>} [registry=TOOL_METADATA] - Registry to validate
 * @param {string[]} [manifestToolNames] - Tool names to cross-reference against; defaults to the live manifest
 * @returns {void}
 * @throws {Error} When a manifest tool has no entry, an entry names an unknown tool, or an entry is missing a required field
 * @example
 * // Runs automatically at module load. Re-invoke only to validate a
 * // synthetic registry (e.g. in tests):
 * validateRegistry({ list_tools: TOOL_METADATA.list_tools }, ['list_tools']);
 */
function validateRegistry(registry = TOOL_METADATA, manifestToolNames) {
  const toolNames = manifestToolNames || getManifestToolNames();
  const toolNameSet = new Set(toolNames);
  const registryKeys = Object.keys(registry);
  const registryKeySet = new Set(registryKeys);

  // >! Every manifest tool must have a registry entry
  for (const toolName of toolNames) {
    if (!registryKeySet.has(toolName)) {
      throw new Error(`Invalid TOOL_METADATA registry: manifest tool "${toolName}" has no registry entry`);
    }
  }

  // >! Every registry entry must name a tool that actually exists
  for (const key of registryKeys) {
    if (!toolNameSet.has(key)) {
      throw new Error(`Invalid TOOL_METADATA registry: entry "${key}" does not match any tool in availableToolsList`);
    }
  }

  // >! Every registry entry must declare all required fields with a valid shape
  for (const key of registryKeys) {
    const entry = registry[key];
    for (const field of REQUIRED_FIELDS) {
      const value = entry ? entry[field] : undefined;
      if (!isValidField(field, value)) {
        throw new Error(`Invalid TOOL_METADATA entry "${key}": missing or invalid required field "${field}"`);
      }
    }
  }
}

// >! Validate the registry once at module load so a malformed registry fails
// >! initialization fast, matching the agent-asset-types.js convention.
validateRegistry();

/**
 * Get the `annotations` object for a tool.
 *
 * @param {string} toolName - Tool name
 * @returns {ToolAnnotations|undefined} The tool's annotations, or `undefined` when the tool has no registry entry
 * @example
 * generateAnnotations('search_documentation'); // -> { readOnlyHint: true, openWorldHint: false }
 * generateAnnotations('unknown_tool');          // -> undefined
 */
function generateAnnotations(toolName) {
  const entry = TOOL_METADATA[toolName];
  return entry ? entry.annotations : undefined;
}

/**
 * Get the display `title` for a tool.
 *
 * @param {string} toolName - Tool name
 * @returns {string|undefined} The tool's title, or `undefined` when the tool has no registry entry
 * @example
 * generateTitles('search_documentation'); // -> 'Search Atlantis Documentation'
 * generateTitles('unknown_tool');          // -> undefined
 */
function generateTitles(toolName) {
  const entry = TOOL_METADATA[toolName];
  return entry ? entry.title : undefined;
}

/**
 * Get the discovery block for a tool — the subset of its registry entry
 * composed into rendered description text rather than emitted as a wire
 * field (`category`, `keywords`, `relatedTools`, `whenToUse`,
 * `whenNotToUse`, `examples`).
 *
 * @param {string} toolName - Tool name
 * @returns {{category: string, keywords: string[], relatedTools: string[], whenToUse: string, whenNotToUse: string, examples: ToolExample[]}|undefined}
 *   The tool's discovery block, or `undefined` when the tool has no registry entry
 * @example
 * getDiscoveryBlock('search_documentation');
 * // -> { category: 'documentation', keywords: [...], relatedTools: [...], whenToUse: '...', whenNotToUse: '...', examples: [...] }
 */
function getDiscoveryBlock(toolName) {
  const entry = TOOL_METADATA[toolName];
  if (!entry) {
    return undefined;
  }
  const { category, keywords, relatedTools, whenToUse, whenNotToUse, examples } = entry;
  return { category, keywords, relatedTools, whenToUse, whenNotToUse, examples };
}

